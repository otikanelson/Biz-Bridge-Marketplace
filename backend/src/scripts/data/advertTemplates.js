// ========== HELPER FUNCTIONS ==========

/**
 * Hash function to deterministically select images for a service
 */
export function hashServiceId(serviceId) {
  let hash = 0;
  const idStr = serviceId.toString();
  for (let i = 0; i < idStr.length; i++) {
    hash = ((hash << 5) - hash) + idStr.charCodeAt(i);
    hash = hash & hash; // Convert to 32bit integer
  }
  return Math.abs(hash);
}

/**
 * Get feature template for category
 */
export function getFeatureTemplate(category, serviceId) {
  const templates = FEATURE_TEMPLATES[category] || FEATURE_TEMPLATES['default'];
  const hash = hashServiceId(serviceId);
  return templates[hash % templates.length];
}

/**
 * Get image text variant
 */
export function getImageTextVariant(position, index, serviceId) {
  const variants = IMAGE_TEXT_VARIANTS[position];
  const hash = hashServiceId(serviceId);
  const template = variants[index % variants.length];
  const textVariant = template.textVariants[hash % template.textVariants.length];
  return { titlePrefix: template.titlePrefix, text: textVariant };
}

/**
 * Get images for category
 */
export function getCategoryImages(category, serviceId, count = 3) {
  const images = CATEGORY_IMAGES[category] || CATEGORY_IMAGES['Other'];
  const hash = hashServiceId(serviceId);
  const startIndex = hash % images.length;
  
  const selectedImages = [];
  for (let i = 0; i < count; i++) {
    selectedImages.push(images[(startIndex + i) % images.length]);
  }
  
  return selectedImages;
}
